NARR = ['Busy day, but no time to stop? Take one slow breath with me right now.',
        "Look up. Name three things you can see, and 'notice' how your shoulders drop."]


def uuid(n):
    return f'00000000-0000-4000-8000-{n:012d}'


def packet(shots_dir):
    """a packet in the caller's shape with one generated file per shot in shots_dir"""
    made = []
    for k, text in enumerate(NARR, 1):
        data = f'synthetic shot {k}'.encode()
        with open(os.path.join(shots_dir, f'shot-{k}.mp4'), 'wb') as fh:
            fh.write(data)
        made.append({'operationId': uuid(10 + k), 'providerJobId': f'job-{k}', 'storagePath': f'episodes/x/shot-{k}.mp4',
                     'url': f'https://example.invalid/shot-{k}.mp4', 'sha256': hashlib.sha256(data).hexdigest(), 'narration': text})
    prov = {'source': 'production', 'episodeId': uuid(1), 'seriesId': uuid(2), 'productionId': uuid(3),
            'packetSha256': 'a' * 64, 'scriptSha256': 'b' * 64,
            'creativeReview': {'status': 'passed', 'inputSha256': 'c' * 64, 'profileVersion': 'v1'},
            'approval': {'approvedAt': '2026-11-04T10:00:00Z'}, 'shots': made}
    return {'shots': [{'narration': t} for t in NARR], 'provenance': prov}


class Packet(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.shots, self.out = os.path.join(self.tmp.name, 'shots'), os.path.join(self.tmp.name, 'out')
        os.makedirs(self.shots)
        self.pk = packet(self.shots)
        seen = mock.patch.object(R, 'clean_from', return_value=(None, 'clean opening'))   # the shots are not real video
        self.opening = seen.start()
        self.addCleanup(seen.stop)

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, pk):
        p = os.path.join(self.tmp.name, 'packet.json')
        with open(p, 'w', encoding='utf-8') as fh:
            json.dump(pk, fh)
        return p

    def refused(self, pk, *extra):
        """run the entry point; it must exit 2 before make_reel is reached. -> the message"""
        argv = ['render_packet.py', self.write(pk), '--shots', self.shots, '--out', self.out, *extra]
        ran, err = mock.Mock(return_value=0), io.StringIO()
        with mock.patch.object(sys, 'argv', argv), mock.patch.object(R.subprocess, 'call', ran), \
                mock.patch.object(sys, 'stderr', err), self.assertRaises(SystemExit) as cm:
            R.main()
        ran.assert_not_called()
        self.assertEqual(cm.exception.code, 2)
        return err.getvalue()

    def test_a_detected_unclean_opening_becomes_the_shots_clean_from_and_every_note_is_kept(self):
        self.opening.side_effect = lambda f: (.792, 'soft object settled at frame 19') if f.endswith('shot-1.mp4') else (None, 'clean opening')
        spec_path, _ = R.convert(self.write(self.pk), self.shots, self.out, 'bold', 'reels')
        with open(spec_path, encoding='utf-8') as fh:
            shots = json.load(fh)['shots']
        self.assertEqual(shots[0]['clean_from'], .792)
        self.assertNotIn('clean_from', shots[1])
        with open(os.path.join(self.out, 'openings.json'), encoding='utf-8') as fh:
            notes = json.load(fh)
        self.assertEqual([n['note'] for n in notes], ['soft object settled at frame 19', 'clean opening'])
        self.assertEqual([n['clean_from'] for n in notes], [.792, None])

    def test_a_file_whose_sha256_differs_refuses_the_run_naming_the_shot(self):
        with open(os.path.join(self.shots, 'shot-2.mp4'), 'ab') as fh:
            fh.write(b'!')
        msg = self.refused(self.pk)
        self.assertIn('shot 2', msg)
        self.assertIn(uuid(12), msg)

    def test_a_missing_file_refuses_the_run_naming_the_shot(self):
        os.remove(os.path.join(self.shots, 'shot-1.mp4'))
        msg = self.refused(self.pk)
        self.assertIn('shot 1', msg)
        self.assertIn(uuid(11), msg)

    def test_two_files_with_the_shot_sha256_are_ambiguous(self):
        with open(os.path.join(self.shots, 'shot-1.mp4'), 'rb') as fh, open(os.path.join(self.shots, 'copy.mp4'), 'wb') as dst:
            dst.write(fh.read())
        msg = self.refused(self.pk)
        self.assertIn('shot 1', msg)
        self.assertIn('copy.mp4', msg)

    def test_narration_that_is_not_the_approved_narration_is_refused(self):
        self.pk['shots'][1]['narration'] = 'Look up.'
        msg = self.refused(self.pk)
        self.assertIn('shot 2', msg)
        self.assertIn('narration', msg)

    def test_a_shot_count_that_differs_from_the_produced_shots_is_refused(self):
        self.pk['shots'].pop()
        self.assertIn('2 produced shots', self.refused(self.pk))

    def test_a_shot_that_matches_its_sha256_but_cannot_be_decoded_is_refused_naming_it(self):
        self.opening.side_effect = openings.clean_from          # the real detector on bytes that are not video
        msg = self.refused(self.pk)
        self.assertIn('shot 1', msg)
        self.assertIn(uuid(11), msg)
        self.assertIn('cannot be decoded', msg)

    def test_a_packet_that_is_not_json_is_refused(self):
        p = os.path.join(self.tmp.name, 'packet.json')
        with open(p, 'w', encoding='utf-8') as fh:
            fh.write('{"shots": [')
        argv = ['render_packet.py', p, '--shots', self.shots, '--out', self.out]
        with mock.patch.object(sys, 'argv', argv), mock.patch.object(R.subprocess, 'call') as ran, \
                mock.patch.object(sys, 'stderr', io.StringIO()) as err, self.assertRaises(SystemExit) as cm:
            R.main()
        ran.assert_not_called()
        self.assertEqual(cm.exception.code, 2)
        self.assertIn('packet refused', err.getvalue())

    def test_usage_errors_exit_2(self):
        for mod, argv in ((R, ['render_packet.py', self.write(self.pk)]), (M, ['make_reel.py', 'x.json'])):
            with mock.patch.object(sys, 'argv', argv), mock.patch.object(sys, 'stderr', io.StringIO()), \
                    self.assertRaises(SystemExit) as cm:
                mod.main()
            self.assertEqual(cm.exception.code, 2, mod.__name__)

    def test_make_reels_exit_code_is_passed_on_and_a_signal_or_unknown_code_is_a_stage_failure(self):
        argv = ['render_packet.py', self.write(self.pk), '--shots', self.shots, '--out', self.out]
        for got, want in ((0, 0), (1, 1), (2, 2), (3, 3), (-9, 3), (7, 3)):
            with mock.patch.object(sys, 'argv', argv), mock.patch.object(R.subprocess, 'call', return_value=got), \
                    self.assertRaises(SystemExit) as cm:
                R.main()
            self.assertEqual(cm.exception.code, want, got)

    def test_a_packet_reel_check_would_refuse_is_refused_before_any_stage_runs(self):
        self.pk['provenance']['creativeReview']['status'] = 'pending'
        self.assertIn('creative review is pending', self.refused(self.pk))

    def test_the_spec_cuts_the_matched_files_in_packet_order_with_provenance_and_no_sfx(self):
        spec_path, _ = R.convert(self.write(self.pk), self.shots, self.out, 'cool-girl', 'tiktok')
        self.assertEqual(spec_path, os.path.join(self.out, 'packet.reel.json'))
        with open(spec_path, encoding='utf-8') as fh:
            sp = json.load(fh)
        self.assertEqual([s['file'] for s in sp['shots']], [os.path.join(os.path.abspath(self.shots), f'shot-{k}.mp4') for k in (1, 2)])
        self.assertEqual([s['narration'] for s in sp['shots']], NARR)
        self.assertTrue(all(set(s) == {'file', 'narration'} for s in sp['shots']))   # no caption_top: faces.py places it
        self.assertEqual(sp['provenance'], self.pk['provenance'])
        self.assertEqual(Q.provenance_problems(sp, require=True), [])
        self.assertEqual((sp['look'], sp['platform'], sp['sfx'], sp['slug']), ('cool-girl', 'tiktok', False, 'ep-00000000'))
        self.assertNotIn('sentences', sp)

    def test_look_and_platform_default_to_bold_reels(self):
        argv = ['render_packet.py', self.write(self.pk), '--shots', self.shots, '--out', self.out]
        with mock.patch.object(sys, 'argv', argv), mock.patch.object(R.subprocess, 'call', return_value=0):
            with self.assertRaises(SystemExit):
                R.main()
        with open(os.path.join(self.out, 'packet.reel.json'), encoding='utf-8') as fh:
            sp = json.load(fh)
        self.assertEqual((sp['look'], sp['platform']), ('bold', 'reels'))

    def test_make_reel_runs_with_provenance_required_and_the_expected_text_and_its_exit_code_is_returned(self):
        argv = ['render_packet.py', self.write(self.pk), '--shots', self.shots, '--out', self.out, '--from', 'build', '--to', 'check']
        ran = mock.Mock(return_value=1)
        with mock.patch.object(sys, 'argv', argv), mock.patch.object(R.subprocess, 'call', ran), self.assertRaises(SystemExit) as cm:
            R.main()
        self.assertEqual(cm.exception.code, 1)
        cmd = ran.call_args[0][0]
        self.assertEqual(cmd[:4], [sys.executable, os.path.join(ROOT, 'scripts', 'make_reel.py'),
                                   os.path.join(self.out, 'packet.reel.json'), '--out'])
        self.assertIn('--require-provenance', cmd)
        self.assertEqual(cmd[cmd.index('--expect-text') + 1], os.path.join(self.out, 'expected-text.txt'))
        self.assertEqual((cmd[cmd.index('--from') + 1], cmd[cmd.index('--to') + 1]), ('build', 'check'))

    def test_expected_text_is_every_caption_chunk_the_build_puts_on_screen(self):
        spec_path, text_path = R.convert(self.write(self.pk), self.shots, self.out, 'bold', 'reels')
        with open(text_path, encoding='utf-8') as fh:
            lines = [ln.rstrip('\n') for ln in fh]
        self.assertEqual(lines[:4], ['Busy day, but', 'no time', 'to stop?', 'Take one slow'])   # default_chunks(7): 3,2 + 2; (8): 3,3 + 2
        with open(spec_path, encoding='utf-8') as fh:
            sp = json.load(fh)
        page, segs = build(sp)
        shown = [' '.join(seg['tokens'][i:i + n]) for seg in segs
                 for i, n in zip(*starts(B.default_chunks(len(seg['tokens']))))]
        self.assertEqual(lines, shown)
        self.assertEqual(Q.missing_text(page, lines), [])
        self.assertIn('tl.fromTo', page)

    def test_sfx_false_keeps_sound_effects_out_of_the_build(self):
        _, _ = R.convert(self.write(self.pk), self.shots, self.out, 'bold', 'reels')
        with open(os.path.join(self.out, 'packet.reel.json'), encoding='utf-8') as fh:
            sp = json.load(fh)
        page, _ = build(sp, sfx={'whoosh-short'})          # the files are there; the spec says no
        self.assertNotIn('<audio id="sfx', page)
        page, _ = build({**sp, 'sfx': True}, sfx={'whoosh-short'})
        self.assertIn('<audio id="sfx', page)

    def test_sfx_false_copies_no_sound_effect_files_into_the_project(self):
        spec_path, _ = R.convert(self.write(self.pk), self.shots, self.out, 'bold', 'reels')
        with mock.patch.object(M, 'vendor_gsap'):
            M.setup(spec_path, self.out)
            self.assertFalse(os.path.exists(os.path.join(self.out, 'assets', 'sfx')))
            with open(spec_path, encoding='utf-8') as fh:
                sp = json.load(fh)
            del sp['sfx']
            on = os.path.join(self.tmp.name, 'on.reel.json')
            with open(on, 'w', encoding='utf-8') as fh:
                json.dump(sp, fh)
            M.setup(on, os.path.join(self.tmp.name, 'on'))
        self.assertTrue(os.path.isdir(os.path.join(self.tmp.name, 'on', 'assets', 'sfx')))   # without the field: as before


class ExitCodes(unittest.TestCase):
    """0 checks pass, 1 a QA check failed, 2 refused, 3 a pipeline stage failed (its own code printed)"""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def exits(self, fn, *a):
        """-> (exit code, stdout) of fn(*a), which must exit"""
        out = io.StringIO()
        with mock.patch.object(sys, 'stdout', out), self.assertRaises(SystemExit) as cm:
            fn(*a)
        return cm.exception.code, out.getvalue()

    def test_a_stage_that_fails_exits_3_and_prints_its_own_code(self):
        code, out = self.exits(M.run, 'faces', [sys.executable, '-c', 'import sys; sys.exit(7)'])
        self.assertEqual(code, 3)
        self.assertIn('faces: exit 7', out)

    def test_an_overlays_render_that_fails_exits_3_and_its_output_is_printed(self):
        done = [mock.Mock(returncode=0, stdout='film ok\n', stderr=''), mock.Mock(returncode=5, stdout='overlay boom\n', stderr='trace\n')]
        with mock.patch.object(M.subprocess, 'run', side_effect=done):
            code, out = self.exits(M.render_both, ['film'], ['overlays'], self.tmp.name)
        self.assertEqual(code, 3)
        self.assertIn('overlay boom', out)
        self.assertIn('trace', out)
        self.assertIn('overlays exit 5', out)

    def test_a_film_render_that_fails_exits_3(self):
        with mock.patch.object(M.subprocess, 'run', return_value=mock.Mock(returncode=1, stdout='film boom\n', stderr='')):
            code, out = self.exits(M.render_both, ['film'], ['overlays'], self.tmp.name)
        self.assertEqual((code, 'film boom' in out), (3, True))

    def test_the_check_stage_passes_on_reel_checks_0_and_1_and_anything_else_is_3(self):
        spec = {'slug': 's', 'shots': []}
        argv = ['make_reel.py', 'x.json', '--out', self.tmp.name, '--from', 'check']
        for got, want in ((0, 0), (1, 1), (3, 3), (-9, 3)):
            ran = [mock.Mock(returncode=0), mock.Mock(returncode=got)]          # check_cuts, then reel_check
            with mock.patch.object(sys, 'argv', argv), mock.patch.object(M, 'setup', return_value=spec), \
                    mock.patch.object(M.subprocess, 'run', side_effect=ran):
                code, _ = self.exits(M.main)
            self.assertEqual(code, want, got)

    def test_a_shot_the_spec_names_that_is_missing_is_refused(self):
        p = os.path.join(self.tmp.name, 'r.json')
        with open(p, 'w', encoding='utf-8') as fh:
            json.dump({'shots': [{'file': 'gone.mp4', 'narration': 'Hi.'}]}, fh)
        with mock.patch.object(sys, 'stderr', io.StringIO()) as err, self.assertRaises(SystemExit) as cm:
            M.setup(p, os.path.join(self.tmp.name, 'proj'))
        self.assertEqual(cm.exception.code, 2)
        self.assertIn('gone.mp4', err.getvalue())

    def test_no_gsap_to_vendor_exits_3(self):
        with mock.patch.dict(os.environ, {'VIDEO_EDIT_GSAP': ''}), \
                mock.patch.object(M.urllib.request, 'urlopen', side_effect=OSError('offline')):
            code, out = self.exits(M.vendor_gsap, os.path.join(self.tmp.name, 'vendor'))
        self.assertEqual(code, 3)
        self.assertIn('could not get GSAP', out)

    def test_a_crash_exits_3_not_1(self):
        def boom():
            raise RuntimeError('boom')
        with mock.patch.object(sys, 'stderr', io.StringIO()) as err, self.assertRaises(SystemExit) as cm:
            skillenv.main_or_3(boom)
        self.assertEqual(cm.exception.code, 3)
        self.assertIn('RuntimeError: boom', err.getvalue())
        with self.assertRaises(SystemExit) as cm:
            skillenv.main_or_3(lambda: sys.exit(1))
        self.assertEqual(cm.exception.code, 1)

    def test_reel_check_crashing_exits_3_so_it_is_not_read_as_a_qa_failure(self):
        p = subprocess.run([sys.executable, os.path.join(ROOT, 'scripts', 'reel_check.py'), self.tmp.name], **skillenv.TEXT)
        self.assertEqual(p.returncode, 3, p.stderr)
        self.assertIn('FileNotFoundError', p.stderr)


def starts(chunks):
    """([first word index], [count]) for a chunk list"""
    ix, i = [], 0
    for n, _ in chunks:
        ix.append(i); i += n
    return ix, [n for n, _ in chunks]


def build(sp, sfx=()):
    """B.build on synthetic words for the spec's narration (no sentences, so default chunks and no holds)"""
    words, sil, durs, t = {}, {}, {}, 0
    for k, s in enumerate(sp['shots'], 1):
        toks = s['narration'].split()
        words[f'c{k}'] = [{'text': w, 'start': round(.5 + j * .3, 3), 'end': round(.75 + j * .3, 3)} for j, w in enumerate(toks)]
        end = .5 + len(toks) * .3
        sil[f'c{k}'] = [[0, .5], [end, end + 2]]
        durs[f'c{k}'] = end + 2
    segs, fr = [], 0
    for e in E.plan(sp, words, sil, durs):
        n = round((e['out'] - e['in']) * 30)
        segs.append({**e, 'src_in': e['in'], 'src_out': e['out'], 'frame': fr, 'frames': n})
        fr += n
    page, _, _ = B.build(sp, B.load_look(sp['look']), sp['platform'], segs, words, [], fr / 30 + 1.5, sfx=sfx)
    return page, segs


